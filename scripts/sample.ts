// Scans Mastodon's repository (live), asks endoflife.date for each product, and writes:
//  public/samples/mastodon-<date>.json  a frozen copy (findings + release data) for the app's sample button
//  docs/mastodon.json + templates/_shared/example.ts  the values the templates' sample uses
// Run: node --experimental-strip-types scripts/sample.ts
import { writeFileSync } from "node:fs";
import { WANTED, detect, resolve, toPlan, type Release } from "../templates/_shared/eol.ts";

const REPO = "mastodon/mastodon";
const AS_OF = "2026-11-20";
const gh = (path: string) => fetch(`https://api.github.com/repos/${REPO}/${path}`, { headers: { Accept: "application/vnd.github+json" } }).then((r) => r.json());

const head = await gh("commits/main");
const tree = await gh(`git/trees/${head.sha}?recursive=1`);
const paths = (tree.tree as Array<{ path: string; type: string }>).filter((t) => t.type === "blob" && WANTED(t.path)).map((t) => t.path);
const files = await Promise.all(paths.map(async (path) => ({ path, text: await fetch(`https://raw.githubusercontent.com/${REPO}/${head.sha}/${path}`).then((r) => r.text()) })));
const findings = detect(files);
const products = [...new Set(findings.map((f) => f.product))];
const releases: Record<string, Release[]> = {};
for (const p of products) {
  const res = await fetch(`https://endoflife.date/api/v1/products/${p}`);
  if (res.ok) releases[p] = (await res.json()).result.releases;
}
// Made-up owners, so the notice has someone to go to.
const OWNERS: Record<string, string> = { postgresql: "Platform team", redis: "Platform team", debian: "Platform team", ubuntu: "Platform team", elasticsearch: "Search team", nodejs: "Web team", ruby: "Web team" };
for (const f of findings) f.owner = OWNERS[f.product];

const date = AS_OF;
writeFileSync(new URL(`../public/samples/mastodon-${date}.json`, import.meta.url), JSON.stringify({ repo: `https://github.com/${REPO}`, commit: head.sha, read: date, files: paths, findings, releases }) + "\n");
const plan = toPlan(resolve(findings, (p) => releases[p], AS_OF), { project: "Mastodon", source: `github.com/${REPO} at ${head.sha.slice(0, 7)}`, asOf: AS_OF, team: "Platform team, Northwind Social", recipient: "Platform team" });
const json = JSON.stringify(plan, null, 2);
writeFileSync(new URL("../docs/mastodon.json", import.meta.url), `${json}\n`);
writeFileSync(
  new URL("../templates/_shared/example.ts", import.meta.url),
  `// The sample: Mastodon's repository (github.com/${REPO}) read on ${AS_OF}, dates from endoflife.date.\n// Generated by scripts/sample.ts. The owners and "Northwind Social" are made up.\nconst example = ${json};\n\nexport default example;\n`,
);
console.log(head.sha.slice(0, 7), paths.length, "files,", findings.length, "findings,", plan.items.length, "items");
